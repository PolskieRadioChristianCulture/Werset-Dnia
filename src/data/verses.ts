export function getRandomVerse(): BibleVerse {
  const index = Math.floor(Math.random() * BIBLE_VERSES.length);
  return BIBLE_VERSES[index];
}

export function getVerseBySlug(slug: string): BibleVerse | undefined {
  const clean = slug.toLowerCase().trim();
  return BIBLE_VERSES.find(v => v.slug === clean || v.id.toLowerCase() === clean);
}

export function getVerseById(id: string): BibleVerse | undefined {
  return BIBLE_VERSES.find(v => v.id === id);
}

// Clean Polish text for fuzzy matching (remove diacritics)
export function normalizeText(text: string): string {
  return text
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/ł/g, 'l')
    .replace(/Ł/g, 'l')
    .trim();
}

/**
 * Normalizes biblical citations for comparison:
 * Handles "Mateusz 11 wer. 28", "Mateusz 11, 28", "Mt 11:28", "Mateusza 11 28", etc.
 */
export function normalizeBiblicalQuery(text: string): string {
  return normalizeText(text)
    .replace(/\b(wersety?|wer|w|rozdzia[lł]y?|rozdz?|r)\b\.?/gi, ' ')
    .replace(/[:,\.\-\/]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * Intelligent local search engine:
 * 1. Checks exact reference matches (e.g. "Mateusz 11 wer. 28", "Mateusz 11:28", "Mt 11, 28", "Psalm 23")
 * 2. Checks thematic keywords and tags
 * 3. Checks verse text matching
 */
export function searchBibleVerses(query: string): BibleVerse[] {
  const q = normalizeText(query);
  if (!q) return [];

  const bibQ = normalizeBiblicalQuery(query);

  // Check exact/near reference matches
  const refMatches: { verse: BibleVerse; score: number }[] = [];

  for (const item of BIBLE_VERSES) {
    let score = 0;
    const refNorm = normalizeText(item.reference);
    const bookNorm = normalizeText(item.book);
    const bookShortNorm = normalizeText(item.bookShort);
    const textNorm = normalizeText(item.text);
    const slugNorm = normalizeText(item.slug);

    // Canonical reference representations
    const refBib = normalizeBiblicalQuery(item.reference); // e.g. "mateusz 11 28"
    const shortBib = normalizeBiblicalQuery(`${item.bookShort} ${item.chapter} ${item.verse}`); // e.g. "mt 11 28"
    const fullBib = normalizeBiblicalQuery(`${item.book} ${item.chapter} ${item.verse}`); // e.g. "ewangelia wg sw mateusza 11 28"
    const chapterBib = normalizeBiblicalQuery(`${item.reference.split(':')[0]}`); // e.g. "mateusz 11"
    const shortChapterBib = normalizeBiblicalQuery(`${item.bookShort} ${item.chapter}`); // e.g. "mt 11"

    // Extract base book names without grammatical endings for inflected matching (e.g. "mateusza" -> "mateusz")
    const refBookBase = normalizeBiblicalQuery(item.reference.split(' ')[0]);

    // Exact or near biblical citation match (highest priority)
    if (bibQ === refBib || bibQ === shortBib || bibQ === fullBib || refNorm === q || slugNorm === q) {
      score += 250;
    } else if (
      (bibQ.includes(refBib) || refBib.includes(bibQ)) ||
      (bibQ.includes(shortBib) || shortBib.includes(bibQ))
    ) {
      score += 180;
    } else if (
      bibQ.startsWith(refBookBase) &&
      bibQ.includes(String(item.chapter)) &&
      bibQ.includes(String(item.verse))
    ) {
      score += 170;
    } else if (refNorm.includes(q)) {
      score += 60;
    } else if (bibQ === chapterBib || bibQ === shortChapterBib) {
      score += 90;
    } else if (bibQ.includes(chapterBib) || bibQ.includes(shortChapterBib)) {
      score += 70;
    } else if (q.includes(bookNorm) || q.includes(bookShortNorm)) {
      score += 40;
    }

    // Check tags
    for (const tag of item.tags) {
      const tagNorm = normalizeText(tag);
      if (tagNorm === q) {
        score += 50;
      } else if (tagNorm.includes(q) || q.includes(tagNorm)) {
        score += 25;
      }
    }

    // Category match
    const catNorm = normalizeText(item.category);
    if (catNorm === q || q.includes(catNorm)) {
      score += 35;
    }

    // Content text match
    if (textNorm.includes(q)) {
      score += 20;
    }

    // Common synonyms / emotional state mapping:
    if (q.includes('ciezko') || q.includes('smut') || q.includes('depres') || q.includes('placz') || q.includes('bol')) {
      if (item.category === 'pocieszenie' || item.tags.includes('jest mi ciezko')) score += 30;
    }
    if (q.includes('strach') || q.includes('lek') || q.includes('boje') || q.includes('obaw')) {
      if (item.category === 'sila' || item.category === 'ochrona' || item.tags.includes('strach') || item.tags.includes('lek')) score += 30;
    }
    if (q.includes('malzen') || q.includes('rodzin') || q.includes('zona') || q.includes('maz')) {
      if (item.category === 'milosc' || item.tags.includes('malzenstwo')) score += 40;
    }
    if (q.includes('zauf') || q.includes('zawierzen')) {
      if (item.category === 'wiara' || item.tags.includes('zaufanie')) score += 35;
    }

    if (score > 0) {
      refMatches.push({ verse: item, score });
    }
  }

  // Sort descending by score
  refMatches.sort((a, b) => b.score - a.score);
  return refMatches.map(m => m.verse);
}
